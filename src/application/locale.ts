export const chromeCopy = (locale: Locale) => CHROME[locale];

export const themeLabel = (slug: string, locale: Locale): string =>
  THEME_LABELS[locale][slug] ?? slug;

export const countryLabel = (country: string, locale: Locale): string => {
  if (locale === 'so') return COUNTRY_LABELS_SO[country] ?? country;
  if (locale === 'ar') return COUNTRY_LABELS_AR[country] ?? country;
  return country;
};

export const continentLabel = (continent: string, locale: Locale): string =>
  CONTINENT_LABELS[locale][continent] ?? continent;

export const formatLocaleDate = (iso: string, locale: Locale): string => {
  const date = new Date(`${iso}T00:00:00Z`);
  if (locale === 'ar') {
    return new Intl.DateTimeFormat('ar', {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
      timeZone: 'UTC',
    }).format(date);
  }
  if (locale !== 'so') {
    return new Intl.DateTimeFormat('en-GB', {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
      timeZone: 'UTC',
    }).format(date);
  }
  return `${date.getUTCDate()} ${MONTHS_SO[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
};

export const mapLayerLabel = (
  id: 'streets' | 'satellite' | 'terrain',
  locale: Locale,
): string => {
  const copy = chromeCopy(locale);
  if (id === 'streets') return copy.basemapStreets;
  if (id === 'satellite') return copy.basemapSatellite;
  return copy.basemapTerrain;
};

export const localizeCreditText = (text: string, locale: Locale): string => {
  if (locale === 'en') return text;
  let next = text.replace(/^Source:/, `${CHROME[locale].sourceWord}:`);
  if (locale === 'so') {
    next = next.replace(/\bPhoto:\s*/gi, 'Sawir: ').replace(/\bPhoto page\b/gi, 'Bogga sawirka');
  } else if (locale === 'ar') {
    next = next.replace(/\bPhoto:\s*/gi, 'صورة: ').replace(/\bPhoto page\b/gi, 'صفحة الصورة');
  }
  return next;
};

export const hazardTitle = (
  id: 'floods' | 'droughts' | 'heat-waves' | 'el-nino' | 'la-nina',
  copy: ReturnType<typeof chromeCopy>,
): string => {
  if (id === 'floods') return copy.floods;
  if (id === 'droughts') return copy.droughts;
  if (id === 'heat-waves') return copy.heatWaves;
  if (id === 'el-nino') return copy.elNino;
  return copy.laNina;
};
