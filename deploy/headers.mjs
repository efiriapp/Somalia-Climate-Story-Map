/**
 * HTTP headers for the live site. Used in two places so they are tested
 * before upload:
 *   - vite.config.ts `preview.headers` (npm run preview)
 *   - the .htaccess written into dist/ at build time (Hostinger / Apache / LiteSpeed)
 *
 * If you add an embed or a map source on another domain, add it here too,
 * otherwise the browser will block it.
 */
const MAP_HOSTS = [
  'https://tiles.openfreemap.org',
  'https://tiles.maps.eox.at',
  'https://elevation-tiles-prod.s3.amazonaws.com',
  // Plain image tiles for browsers without WebGL2.
  'https://tile.openstreetmap.org',
];

/** Live data for Flood Watch and Drought Watch (free, non-commercial, CC BY 4.0). */
const DATA_HOSTS = [
  'https://flood-api.open-meteo.com',
  'https://archive-api.open-meteo.com',
  'https://api.open-meteo.com',
];

export const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self'",
  "worker-src 'self' blob:",
  "child-src 'self' blob:",
  // React style attributes and map libraries set inline styles.
  "style-src 'self' 'unsafe-inline'",
  `img-src 'self' data: blob: ${MAP_HOSTS.join(' ')}`,
  `connect-src 'self' ${[...MAP_HOSTS, ...DATA_HOSTS].join(' ')}`,
  "font-src 'self' data:",
  'frame-src https://www.youtube-nocookie.com https://www.facebook.com',
  "media-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'self'",
].join('; ');

export const SECURITY_HEADERS = {
  'Content-Security-Policy': CONTENT_SECURITY_POLICY,
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'X-Frame-Options': 'SAMEORIGIN',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
};

/** Apache/LiteSpeed config written to dist/.htaccess. */
export const htaccess = () => `# Generated by vite.config.ts from deploy/headers.mjs. Edit that file, not this one.
# Works on Hostinger shared hosting (LiteSpeed) and Apache.
# Turn on HTTPS with hPanel > Security > SSL, then hPanel's "Force HTTPS".

Options -Indexes
DirectoryIndex index.html
# Pages use #/ addresses, so any other path is a bad link: show the site.
ErrorDocument 404 /index.html

# Correct types, so the MapLibre worker (.mjs) and modern images load.
AddType text/javascript .js .mjs
AddType image/avif .avif
AddType image/webp .webp
AddType image/svg+xml .svg
AddType font/woff2 .woff2
AddType application/json .json

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/json image/svg+xml
</IfModule>

<IfModule mod_headers.c>
${Object.entries(SECURITY_HEADERS)
  .map(([name, value]) => `  Header always set ${name} "${value}"`)
  .join('\n')}

  # index.html: always check for a new version, so updates show at once.
  <FilesMatch "^(index\\.html)?$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  # Built files carry a content hash in their name, so they never change.
  <FilesMatch "-[A-Za-z0-9_-]{8}\\.(js|css|woff2?|svg)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  # Photos and logos keep their names when replaced: cache for a week.
  <FilesMatch "\\.(jpe?g|png|webp|avif)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
  <FilesMatch "\\.mjs$">
    Header set Cache-Control "public, max-age=86400"
  </FilesMatch>
</IfModule>
`;
