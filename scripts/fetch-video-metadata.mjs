/**
 * Looks up title, channel and publish date for every YouTube video used in
 * src/content and writes src/content/video-sources.ts, so each video can be
 * cited properly (APA 7 style). Uses YouTube's public oEmbed endpoint (no key)
 * and the date published on the public watch page.
 *
 *   npm run videos:fetch
 *
 * Facebook videos cannot be looked up without an account; their citations are
 * kept by hand in src/content/media-sources.ts.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'src', 'content');
const outFile = join(contentDir, 'video-sources.ts');
const UA = 'ICE-Climate-Story-Map/1.0 (video citations; educational nonprofit)';

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

const ID = /https:\/\/(?:youtu\.be\/|(?:www\.)?youtube\.com\/(?:watch\?v=|shorts\/|embed\/))([A-Za-z0-9_-]{11})/g;
const ids = new Set();
for (const file of walk(contentDir).filter((f) => f.endsWith('.ts') && !f.endsWith('video-sources.ts'))) {
  for (const match of readFileSync(file, 'utf8').matchAll(ID)) ids.add(match[1]);
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const videos = {};
const problems = [];

for (const id of [...ids].sort()) {
  const watchUrl = `https://www.youtube.com/watch?v=${id}`;
  try {
    const oembed = await fetch(
      `https://www.youtube.com/oembed?url=${encodeURIComponent(watchUrl)}&format=json`,
      { headers: { 'User-Agent': UA } },
    );
    if (!oembed.ok) throw new Error(`oEmbed HTTP ${oembed.status} (private or removed?)`);
    const info = await oembed.json();
    const page = await fetch(watchUrl, { headers: { 'User-Agent': UA, 'Accept-Language': 'en' } });
    const html = page.ok ? await page.text() : '';
    const published =
      html.match(/itemprop="datePublished" content="(\d{4}-\d{2}-\d{2})/)?.[1] ??
      html.match(/"publishDate":"(\d{4}-\d{2}-\d{2})/)?.[1] ??
      null;
    if (!published) problems.push(`${id}: no publish date found`);
    videos[id] = {
      title: info.title,
      channel: info.author_name,
      channelUrl: info.author_url,
      published,
      url: watchUrl,
      platform: 'YouTube',
    };
  } catch (error) {
    problems.push(`${id}: ${error.message}`);
  }
  await sleep(500);
}

writeFileSync(
  outFile,
  `// Generated by scripts/fetch-video-metadata.mjs from YouTube oEmbed and public watch pages.
// Do not edit by hand; run \`npm run videos:fetch\` after adding or changing a YouTube video.

export type VideoSource = {
  title: string;
  channel: string;
  channelUrl: string;
  /** ISO date (YYYY-MM-DD) the video was published, when YouTube shows it. */
  published: string | null;
  url: string;
  platform: 'YouTube';
};

export const YOUTUBE_SOURCES: Record<string, VideoSource> = ${JSON.stringify(videos, null, 2)};
`,
);

console.log(`Wrote ${Object.keys(videos).length} of ${ids.size} videos to ${outFile.slice(root.length + 1)}`);
if (problems.length) {
  console.log(`Check by hand:\n  ${problems.join('\n  ')}`);
  process.exitCode = 1;
}
