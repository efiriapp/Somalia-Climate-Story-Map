/**
 * Looks up author, licence and file page for every research photo on
 * Wikimedia Commons and writes src/content/research-image-credits.ts.
 * Creative Commons licences require crediting the author, the licence and
 * the source, so run this again whenever a research photo changes:
 *
 *   node ./scripts/fetch-wikimedia-credits.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RESEARCH_IMAGE_SOURCES } from './research-image-sources.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src', 'content', 'research-image-credits.ts');
const API = 'https://commons.wikimedia.org/w/api.php';
const UA = 'ICE-Climate-Story-Map/1.0 (photo credits; educational nonprofit)';

const plain = (html = '') =>
  html
    .replace(/<[^>]*>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const fetchBatch = async (titles) => {
  const params = new URLSearchParams({
    action: 'query',
    format: 'json',
    formatversion: '2',
    prop: 'imageinfo',
    iiprop: 'extmetadata|url',
    titles: titles.map((title) => `File:${title}`).join('|'),
  });
  const res = await fetch(`${API}?${params}`, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Commons API HTTP ${res.status}`);
  const json = await res.json();
  const normalized = new Map((json.query.normalized ?? []).map((n) => [n.to, n.from]));
  return json.query.pages.map((page) => ({ requested: normalized.get(page.title) ?? page.title, page }));
};

const entries = Object.entries(RESEARCH_IMAGE_SOURCES);
const byTitle = new Map(entries.map(([local, title]) => [`File:${title}`, local]));
const credits = {};
const problems = [];

for (let i = 0; i < entries.length; i += 20) {
  const batch = entries.slice(i, i + 20).map(([, title]) => title);
  for (const { requested, page } of await fetchBatch(batch)) {
    const local = byTitle.get(requested) ?? byTitle.get(page.title);
    const info = page.imageinfo?.[0];
    if (!local || !info) {
      problems.push(`${requested}: not found on Commons`);
      continue;
    }
    const meta = info.extmetadata ?? {};
    const author = plain(meta.Artist?.value) || 'Unknown author';
    const license = plain(meta.LicenseShortName?.value) || 'See file page';
    credits[`/images/research/${local}`] = {
      title: plain(meta.ObjectName?.value) || page.title.replace(/^File:/, '').replace(/\.[a-z]+$/i, ''),
      author,
      license,
      licenseUrl: meta.LicenseUrl?.value || null,
      pageUrl: info.descriptionurl,
    };
    const freeOfAttribution = /public domain|cc0/i.test(license);
    if (author === 'Unknown author' && !freeOfAttribution) problems.push(`${local}: no author listed`);
  }
}

const sorted = Object.fromEntries(Object.entries(credits).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  outFile,
  `// Generated by scripts/fetch-wikimedia-credits.mjs from the Wikimedia Commons API.
// Do not edit by hand; rerun the script when a research photo changes.

export type ImageCredit = {
  title: string;
  author: string;
  license: string;
  licenseUrl: string | null;
  pageUrl: string;
};

export const RESEARCH_IMAGE_CREDITS: Record<string, ImageCredit> = ${JSON.stringify(sorted, null, 2)};
`,
);

console.log(`Wrote ${Object.keys(sorted).length} of ${entries.length} credits to ${outFile.slice(root.length + 1)}`);
if (problems.length) {
  console.log(`Check by hand:\n  ${problems.join('\n  ')}`);
  process.exitCode = 1;
}
